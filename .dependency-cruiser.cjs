// Package graph: each package depends only on the packages in its list.
const allowed = {
  core: [],
  testing: ['core', 'protocol', 'runtime'],
  codecs: ['core'],
  protocol: ['core'],
  runtime: ['core', 'codecs', 'protocol'],
  'transport-memory': ['protocol'],
  'transport-ws': ['protocol'],
  'transport-stdio': ['protocol'],
  'transport-inbox': ['protocol'],
  'tools-node': ['runtime'],
  'model-compat': ['core', 'codecs', 'runtime'],
  'model-pi': ['core', 'codecs', 'runtime'],
  'tools-user': ['core'],
  mcp: ['core', 'runtime'],
  skills: ['core'],
  client: ['core', 'protocol', 'tools-user'],
  'client-react': ['core', 'protocol', 'tools-user', 'client'],
  acp: ['core', 'protocol', 'tools-user', 'client'],
}
const nodeAllowed = ['tools-node', 'transport-inbox', 'transport-ws', 'transport-stdio']
// In `mcp` and `acp`, only the `./node` entry depends on Node: launching local MCP servers, and
// the ACP stream over standard input and output.
const nodeEntries = ['^packages/mcp/src/node\\.ts$', '^packages/acp/src/node\\.ts$']
const alt = (names) => names.map((n) => n.replace(/[-]/g, '\\-')).join('|')
const hub = '^apps/hub/src/'

module.exports = {
  forbidden: [
    ...Object.entries(allowed).map(([name, deps]) => ({
      name: `graph-${name}`,
      severity: 'error',
      from: { path: `^packages/${name}/` },
      to: {
        path: '^packages/([^/]+)/',
        pathNot: [`^packages/(${alt([name, ...deps])})/`],
      },
    })),
    {
      name: 'core-types-only',
      severity: 'error',
      from: { path: '^packages/core/src/' },
      to: { dependencyTypesNot: ['type-only', 'local'] },
    },
    {
      name: 'api-web-standard',
      severity: 'error',
      from: { path: '^packages/', pathNot: [`^packages/(${alt(nodeAllowed)})/`, ...nodeEntries] },
      to: { dependencyTypes: ['core'] },
    },
    {
      name: 'mcp-stdio-in-node',
      severity: 'error',
      from: { path: '^packages/mcp/', pathNot: nodeEntries },
      to: { path: '@modelcontextprotocol/client/dist/stdio' },
    },
    {
      name: 'packages-without-apps',
      severity: 'error',
      from: { path: '^packages/' },
      to: { path: '^apps/' },
    },
    // Hub layers. The pages (`client`, `routes`, `ui`, the router) reach the server only by a
    // dynamic import in a branch that runs on the server.
    {
      name: 'hub-pages-without-server',
      severity: 'error',
      from: { path: `${hub}(client|routes|ui)/|${hub}(client|router)\\.tsx$` },
      to: { path: `${hub}(server|platform)/`, dependencyTypesNot: ['dynamic-import'] },
    },
    // `shared` is read by the pages and the server: it depends on neither.
    {
      name: 'hub-shared-alone',
      severity: 'error',
      from: { path: `${hub}shared/` },
      to: { path: hub, pathNot: `${hub}shared/` },
    },
    // The server is the same on every platform: each platform assembles it, not the reverse.
    {
      name: 'hub-server-without-platform',
      severity: 'error',
      from: { path: `${hub}server/` },
      to: { path: `${hub}(platform|client|routes|ui)/` },
    },
    // A storage backend is reached through the contracts of `data.ts`, and is assembled only by
    // the platform; no backend reaches another.
    {
      name: 'hub-storage-in-platform',
      severity: 'error',
      from: { path: `${hub}server/`, pathNot: `${hub}server/(pg|d1|do)/` },
      to: { path: `${hub}server/(pg|d1|do)/` },
    },
    {
      name: 'hub-storage-apart',
      severity: 'error',
      from: { path: `${hub}server/(pg|d1|do)/` },
      to: { path: `${hub}server/(pg|d1|do)/`, pathNot: '$1' },
    },
    // The shared server runs on Node and on Workers: no driver nor runtime of either, and of
    // Node only `AsyncLocalStorage`, which Workers provides.
    {
      name: 'hub-server-portable',
      severity: 'error',
      from: { path: `${hub}server/`, pathNot: `${hub}server/(pg|d1|do)/` },
      to: {
        path: '^cloudflare:|node_modules/(postgres|undici)/|node_modules/drizzle-orm/(postgres-js|d1)/',
      },
    },
    {
      name: 'hub-server-node-free',
      severity: 'error',
      from: { path: `${hub}server/`, pathNot: `${hub}server/(pg|d1|do)/` },
      to: { dependencyTypes: ['core'], pathNot: '^(node:)?async_hooks$' },
    },
    // The route tree generated by TanStack imports the router, which imports it: this return is
    // only a type import, which the generator requires.
    {
      name: 'no-cycle',
      severity: 'error',
      from: {},
      to: { circular: true, viaNot: 'routeTree\\.gen\\.ts$' },
    },
    // An unresolved import would escape the graph rules: it is refused. The `cloudflare:` modules
    // are provided by the Workers runtime, not by a file.
    {
      name: 'import-resolved',
      severity: 'error',
      from: {},
      to: { couldNotResolve: true, pathNot: '^cloudflare:' },
    },
  ],
  options: {
    doNotFollow: { path: 'node_modules' },
    tsPreCompilationDeps: true,
    tsConfig: { fileName: 'tsconfig.base.json' },
    // The repository packages export their `.ts` sources; without these options, their imports
    // stay unresolved and the graph rules see nothing.
    enhancedResolveOptions: {
      exportsFields: ['exports'],
      conditionNames: ['import', 'default'],
      extensions: ['.ts', '.tsx', '.js', '.mjs', '.cjs'],
    },
    exclude: { path: '(^|/)(test|dist)/' },
  },
}
